-- Cadastro público mínimo da MecaTiger Community.
-- O site pode inserir um cadastro consentido, mas nunca lê a lista de e-mails.

create table if not exists public.community_registrations (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(trim(email)) and char_length(email) between 3 and 320),
  profile_role text not null check (profile_role in ('competidor', 'estudante', 'mentor', 'professor', 'equipe', 'entusiasta')),
  team_or_school text not null check (char_length(trim(team_or_school)) between 2 and 160),
  state text not null check (char_length(trim(state)) between 2 and 80),
  country text not null default 'Brasil' check (char_length(trim(country)) between 2 and 80),
  consent boolean not null default false check (consent = true),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.community_metrics (
  id smallint primary key check (id = 1),
  people_count bigint not null default 0,
  states_count bigint not null default 0,
  countries_count bigint not null default 0,
  students_count bigint not null default 0,
  mentors_count bigint not null default 0,
  updated_at timestamptz not null default timezone('utc', now())
);

insert into public.community_metrics (id)
values (1)
on conflict (id) do nothing;

create or replace function public.refresh_community_metrics()
returns trigger
language plpgsql
security definer
set search_path = ''
as $
begin
  insert into public.community_metrics (
    id, people_count, states_count, countries_count, students_count, mentors_count, updated_at
  )
  select
    1,
    count(*)::bigint,
    count(distinct state) filter (where country = 'Brasil' and state <> 'Exterior')::bigint,
    count(distinct country)::bigint,
    count(*) filter (where profile_role in ('estudante', 'competidor'))::bigint,
    count(*) filter (where profile_role in ('mentor', 'professor'))::bigint,
    timezone('utc', now())
  from public.community_registrations
  on conflict (id) do update set
    people_count = excluded.people_count,
    states_count = excluded.states_count,
    countries_count = excluded.countries_count,
    students_count = excluded.students_count,
    mentors_count = excluded.mentors_count,
    updated_at = excluded.updated_at;
  return null;
end;
$$;

drop trigger if exists refresh_community_metrics_trigger on public.community_registrations;
create trigger refresh_community_metrics_trigger
after insert or update or delete on public.community_registrations
for each statement execute function public.refresh_community_metrics();

alter table public.community_registrations enable row level security;
alter table public.community_metrics enable row level security;

revoke all on public.community_registrations from public, anon, authenticated;
revoke all on sequence public.community_registrations_id_seq from public, anon, authenticated;

drop policy if exists "Visitors can submit a consented registration" on public.community_registrations;

create or replace function public.register_community_member(
  p_email text,
  p_profile_role text,
  p_team_or_school text,
  p_state text,
  p_country text,
  p_consent boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if p_consent is distinct from true then
    raise exception 'Consent is required' using errcode = '42501';
  end if;

  insert into public.community_registrations (
    email, profile_role, team_or_school, state, country, consent
  )
  values (
    lower(trim(p_email)),
    p_profile_role,
    trim(p_team_or_school),
    trim(p_state),
    trim(p_country),
    true
  )
  on conflict (email) do nothing;
end;
$function$;

revoke all on function public.register_community_member(text, text, text, text, text, boolean) from public, anon, authenticated;
grant execute on function public.register_community_member(text, text, text, text, text, boolean) to anon, authenticated;

revoke all on public.community_metrics from public, anon, authenticated;
grant select on public.community_metrics to anon, authenticated;

drop policy if exists "Visitors can read aggregate metrics" on public.community_metrics;
create policy "Visitors can read aggregate metrics"
on public.community_metrics
for select
to anon, authenticated
using (id = 1);

revoke all on function public.refresh_community_metrics() from public, anon, authenticated;
