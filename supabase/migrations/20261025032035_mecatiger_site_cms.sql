-- Meca Tiger CMS: isolated editor grants, editable copy and published photo gallery.
-- Additive only. Not applied to any hosted database in this PR.
-- Membership is granted ONLY out-of-band to a verified Auth user by an authorized operator.
create table if not exists public.meca_site_editors (
  user_id uuid primary key references auth.users(id) on delete cascade,
  granted_at timestamptz not null default now()
);
alter table public.meca_site_editors enable row level security;
revoke all on public.meca_site_editors from public, anon, authenticated;
grant select on public.meca_site_editors to authenticated;
create policy "Editors can read their own grant"
  on public.meca_site_editors for select to authenticated
  using (user_id = (select auth.uid()) and (auth.jwt()->>'is_anonymous') = 'false');

create table if not exists public.meca_site_copy (
  slot text primary key check (slot in (
    'home-intro','projects-intro','community-intro','rede-intro'
  )),
  body text not null check (char_length(btrim(body)) between 8 and 700),
  updated_by uuid not null references auth.users(id),
  updated_at timestamptz not null default now()
);
alter table public.meca_site_copy enable row level security;
revoke all on public.meca_site_copy from public, anon, authenticated;
grant select on public.meca_site_copy to anon, authenticated;
grant insert, update on public.meca_site_copy to authenticated;
create policy "Public reads published copy"
  on public.meca_site_copy for select to anon, authenticated using (true);
create policy "Editors insert copy"
  on public.meca_site_copy for insert to authenticated
  with check (
    updated_by = (select auth.uid())
    and (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );
create policy "Editors update copy"
  on public.meca_site_copy for update to authenticated
  using (
    (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  )
  with check (
    updated_by = (select auth.uid())
    and (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );

-- Public images are expressly intended for publication; do not upload personal photographs without consent.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('meca-site-gallery', 'meca-site-gallery', true, 2097152, array['image/webp'])
on conflict (id) do nothing;

create policy "Verified editors can upload webp gallery assets"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'meca-site-gallery'
    and (auth.jwt()->>'is_anonymous') = 'false'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and name ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}[.]webp$'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );

create table if not exists public.meca_site_gallery (
  id bigint generated by default as identity primary key,
  asset_path text not null unique check (
    asset_path ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}[.]webp$'
  ),
  caption text not null check (char_length(btrim(caption)) between 3 and 160),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.meca_site_gallery enable row level security;
revoke all on public.meca_site_gallery from public, anon, authenticated;
grant select on public.meca_site_gallery to anon, authenticated;
grant insert on public.meca_site_gallery to authenticated;
grant usage, select on sequence public.meca_site_gallery_id_seq to authenticated;
create policy "Public reads approved gallery assets"
  on public.meca_site_gallery for select to anon, authenticated using (true);
create policy "Verified editors add gallery photos"
  on public.meca_site_gallery for insert to authenticated
  with check (
    created_by = (select auth.uid())
    and split_part(asset_path, '/', 1) = (select auth.uid())::text
    and (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );
-- No UPDATE/DELETE grants or policies on editors, gallery or storage objects for browser users.

-- Dynamic text pages and navigation tabs. Text is rendered only through textContent.
create table public.meca_site_pages (
  slug text primary key check (char_length(slug) between 2 and 64 and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null check (char_length(btrim(title)) between 2 and 100),
  nav_label text not null check (char_length(btrim(nav_label)) between 2 and 28),
  summary text not null default '' check (char_length(btrim(summary)) <= 180),
  body text not null check (char_length(btrim(body)) between 8 and 20000),
  cover_path text check (cover_path is null or cover_path ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}[.]webp$'),
  cover_alt text not null default '' check (
    (cover_path is null and cover_alt = '')
    or (cover_path is not null and char_length(btrim(cover_alt)) between 3 and 160)
  ),
  show_in_nav boolean not null default true,
  nav_order integer not null default 100 check (nav_order between 0 and 9999),
  published boolean not null default false,
  updated_by uuid not null references auth.users(id),
  updated_at timestamptz not null default now()
);
create index meca_site_pages_public_nav_idx
  on public.meca_site_pages(nav_order, nav_label) where published and show_in_nav;
alter table public.meca_site_pages enable row level security;
revoke all on public.meca_site_pages from public, anon, authenticated;
grant select on public.meca_site_pages to anon, authenticated;
grant insert, update on public.meca_site_pages to authenticated;
create policy "Public reads published site pages"
  on public.meca_site_pages for select to anon, authenticated using (published = true);
create policy "Editors read all site pages"
  on public.meca_site_pages for select to authenticated using (
    (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );
create policy "Editors create site pages"
  on public.meca_site_pages for insert to authenticated with check (
    updated_by = (select auth.uid())
    and (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );
create policy "Editors update site pages"
  on public.meca_site_pages for update to authenticated
  using (
    (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  )
  with check (
    updated_by = (select auth.uid())
    and (auth.jwt()->>'is_anonymous') = 'false'
    and exists (select 1 from public.meca_site_editors e where e.user_id = (select auth.uid()))
  );
