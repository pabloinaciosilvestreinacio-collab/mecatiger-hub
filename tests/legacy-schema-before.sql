-- production catalog inspection, NOT the original historical migrations.
-- Never apply this fixture to a hosted project or actual users.
create table public.community_registrations (
  id bigint generated by default as identity primary key,
  email text not null unique check (email=lower(trim(email)) and char_length(email) between 3 and 320),
  profile_role text not null check (profile_role in ('competidor','estudante','mentor','professor','equipe','entusiasta')),
  team_or_school text not null check (char_length(trim(team_or_school)) between 2 and 160),
  state text not null check (char_length(trim(state)) between 2 and 80),
  country text not null default 'Brasil' check (char_length(trim(country)) between 2 and 80),
  consent boolean not null default false check (consent=true),
  created_at timestamptz default now()
);
alter table public.community_registrations enable row level security;
create table public.community_metrics (
 id smallint primary key check (id=1),
 people_count bigint default 0, countries_count bigint default 0,
 students_count bigint default 0, mentors_count bigint default 0,
 updated_at timestamptz default now(), states_count bigint default 0
);
alter table public.community_metrics enable row level security;
grant select on public.community_metrics to anon, authenticated;
create policy "Synthetic metric read" on public.community_metrics
  for select to anon, authenticated using (true);

-- Read-only production RPC definition transcribed exclusively into a disposable fixture.
create or replace function public.register_community_member(
 p_email text, p_profile_role text, p_team_or_school text,
 p_state text, p_country text, p_consent boolean
) returns void language plpgsql security definer set search_path to '' as $function$
begin
  if p_consent is distinct from true then
    raise exception 'Consent is required' using errcode='42501';
  end if;
  insert into public.community_registrations
    (email,profile_role,team_or_school,state,country,consent)
  values (lower(trim(p_email)),p_profile_role,trim(p_team_or_school),
          trim(p_state),trim(p_country),true)
  on conflict (email) do nothing;
end; $function$;
revoke all on function public.register_community_member(text,text,text,text,text,boolean) from public;
grant execute on function public.register_community_member(text,text,text,text,text,boolean) to anon, authenticated;

